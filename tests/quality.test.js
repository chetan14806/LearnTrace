const assert = require('node:assert/strict');
process.env.OPENAI_API_KEY = 'stub-key-never-sent';
const { chunkText, readableTopicLabel, createAssessmentAI, createFollowUpAssessmentAI, gradeAssessment, modelAnswer, retrieve, pptxToSlideChunks, playlistIdFromUrl } = require('../server');
const { runPython } = require('../runtime');
const corpus = chunkText('A cycle indicates deadlock when every resource type has one instance. A deadlock cycle involves processes waiting for resources.', { title: 'Graph notes', sourceType: 'document' });
const quiz = { concept: 'Deadlock cycles', question: 'When does a cycle prove deadlock?', options: ['When each resource has one instance', 'When memory is full', 'When a process finishes', 'When no resource is requested'], correctIndex: 0, explanation: 'The passage specifies one instance per resource type.', misconception: 'A cycle is not a general memory-usage indicator.', supportQuote: 'A cycle indicates deadlock when every resource type has one instance.' };
const fake = text => async () => ({ ok: true, json: async () => ({ output: [{ content: [{ type: 'output_text', text }] }] }) });
const failure = async () => { throw new Error('Simulated offline service'); };

(async () => {
  const assessment = await createAssessmentAI('cycle deadlock', corpus, fake(JSON.stringify(quiz)));
  assert.equal(assessment.generator, 'model');
  const correct = assessment.options.indexOf(quiz.options[0]);
  const grade = gradeAssessment(assessment.id, correct);
  assert.equal(grade.correct, true);
  assert.deepEqual(gradeAssessment(assessment.id, correct), grade, 'Retry must be idempotent');
  assert.throws(() => gradeAssessment(assessment.id, (correct + 1) % 4), /already been graded/);
  assert.equal(grade.evidence.text, corpus[0].text, 'Feedback must retain the passage, not only its first sentence');
  const fallback = await createAssessmentAI('cycle deadlock', corpus, failure);
  assert.equal(fallback.generator, 'template');
  gradeAssessment(fallback.id, 0);
  const follow = await createFollowUpAssessmentAI(fallback.id, corpus, failure);
  assert.equal(follow.concept, fallback.concept);
  assert.notDeepEqual(new Set(follow.options), new Set(fallback.options), 'Follow-up must use a different statement');
  gradeAssessment(follow.id, 0);
  await assert.rejects(() => createFollowUpAssessmentAI(follow.id, corpus, failure), /No new source check/);
  const malformed = await createAssessmentAI('cycle deadlock', corpus, fake(JSON.stringify({ ...quiz, explanation: null })));
  assert.equal(malformed.generator, 'template');
  const duplicate = await createAssessmentAI('cycle deadlock', corpus, fake(JSON.stringify({ ...quiz, options: ['a', 'a', 'b', 'c'] })));
  assert.equal(duplicate.generator, 'template');
  const evidence = retrieve('cycle deadlock', corpus);
  const supported = answer => JSON.stringify({ status: 'supported', answer, support: [{ excerpt: 1, quote: corpus[0].text }] });
  const answer = await modelAnswer('When is a cycle conclusive?', evidence, fake(supported('With one instance per resource [1].')));
  assert.deepEqual(answer.citedEvidence, [1]);
  await assert.rejects(() => modelAnswer('When?', evidence, fake(supported('Always [999].'))), /invalid citation/);
  await assert.rejects(() => modelAnswer('When?', evidence, fake(supported('No references here.'))), /support quotation/);
  assert(!readableTopicLabel(['recovery', 'muscle']).includes('deadlock'), 'Generic recovery must not invent an operating-systems topic');
  assert.equal(playlistIdFromUrl('https://example.com/?list=PL123'), null);
  assert.equal(new Set([...corpus, ...chunkText(corpus[0].text, { title: 'Other' })].map(c => c.id)).size, 2);
  const script = "import io,zipfile,base64\nb=io.BytesIO()\nwith zipfile.ZipFile(b,'w') as z:\n z.writestr('ppt/slides/slide2.xml','<p xmlns:a=\"urn:test\"><a:t>Allocation edge</a:t></p>')\n z.writestr('ppt/slides/slide1.xml','<p xmlns:a=\"urn:test\"><a:t>Deadlock cycle</a:t></p>')\nprint(base64.b64encode(b.getvalue()).decode())";
  const { stdout } = await runPython('zipfile', ['-c', script]);
  const slides = await pptxToSlideChunks(Buffer.from(stdout.trim(), 'base64'), 'Short slides');
  assert.equal(slides.length, 2, 'Short slide titles must survive extraction');
  assert.equal(slides[0].text, 'Deadlock cycle');
  assert.match(slides[1].locationLabel, /Slide 2/);
  delete process.env.OPENAI_API_KEY;
  let called = false;
  await createAssessmentAI('cycle', corpus, async () => { called = true; });
  assert.equal(called, false, 'No external model call without credentials');
  console.log('Quality checks passed: model stubs, fallbacks, repeat-safe grading, follow-up variety, citations, topic labels, short PPTX slides and source IDs.');
})().catch(error => { console.error(error); process.exitCode = 1; });
